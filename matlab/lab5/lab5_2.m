disp('--------------------------------------------');
fprintf('Функция: f = -3*x^3+4*x+5\n');
%Локализация корня методом перебора
%Используя символьную математику
syms x;
f=-(3*x.^3)+(4*x)+5;
X=0;
h=0.1;
xh=X+h;
while subs(f, x, X)*subs(f, x, xh)>0
    X=xh;
    xh=X+h;
end
disp("Интервал локализации корня: "+X+" ; "+xh);
disp('--------------------------------------------');
%Расчет решения используя стандартные операторы MATLAB
f=inline('-(3*x^3)+(4*x)+5');
eps = 0.0001; disp("Решение fzero с точностью "+eps+":"); 
[x_fzero,fval,exitflag,output] = fzero(f, X, optimset('Display','off','TolX',eps));
disp("X="+x_fzero); disp("Вывод доп. информации: "); disp(output);
disp("Решение fsolve с точностью "+eps+":");
[xfsolve,fval,exitflag,output] = fsolve(f, X, optimset('Display','off','TolX',eps));
disp("X="+xfsolve); disp("Вывод доп. информации: "); disp(output);
disp('--------------------------------------------');
%Используя символьную математику
syms x;
