disp('--------------------------------------------');

disp("Метод хорд")
f=inline('-(3*x.^3)+(4*x)+5');
f2=inline('-18*x');
disp("Заданная точность:" + eps);
x0=X;
x=0;
N=0;
a=xh;
b=X;
modab=abs(a-b);
%для выполнения условия поменяли местами границы a и b 
if f(a)*f2(a)>0 %Проверка условия сходимости
    while modab>eps
       x=a-(f(a)*(b-a))/(f(b)-f(a));
       if f(a)*f(x)<0
           b=x;
       end
       if f(b)*f(x)<0
           a=x;
       end
       modab=abs(x-x0);
       x0=x;
       N=N+1;
    end    
end  
disp("Полученное X: " + x);
disp("Количество итераций: " + N);
%Проверка решения
disp("Проверка решения уравнения: f(x)= " + f(x));
disp('--------------------------------------------');
%График
