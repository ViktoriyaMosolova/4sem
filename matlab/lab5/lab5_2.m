disp("Решение через символьную математику. X: "+double(solve(f,x,'Real',true)));
disp('--------------------------------------------');

%Метод простых итераций
disp("Метод простых итераций")
f=@(x) -3*x.^3+(4*x)+5;
fd=@(x) -9*x.^2+4;
%fy=(x0-f(x0)/fd(x0))'
fy = @(x0) -(18*x0*(- 3*x0^3 + 4*x0 + 5))/(9*x0^2 - 4)^2;
eps=0.0001;
disp("Заданная точность:" + eps);
x0=xh;
N=0;
%за x0 взята левая граница интервала
if abs(fy(x0))<1 %Проверка условия сходимости
        x=x0-f(x0)/fd(x0);
        while abs(x-x0)>eps
            x0=x;
            x=x0-f(x0)/fd(x0);
            N=N+1;
        end
        disp("Полученное X: " + x);
        disp("Количество итераций: " + N);
end
%Проверка решения
disp("Проверка решения уравнения: f(x)= " + f(x));
disp('--------------------------------------------');
%График
Xstep=X-h:0.0001:xh+h;
f = -(3*Xstep.^3)+(4*Xstep)+5;
